package fsutil

import (
	"os"
	"syscall"
)

// OpenNoFollow is [os.OpenFile] that fails if the last element of path is a
// symlink, which a cloned repository could ship to have the server write to
// another file of the user.
func OpenNoFollow(path string, flag int, perm os.FileMode) (*os.File, error) {
	return os.OpenFile(path, flag|syscall.O_NOFOLLOW, perm)
}
